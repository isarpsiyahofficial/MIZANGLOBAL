def main() -> None:
    changed: list[str] = []
    for path in FILES:
        if not path.exists():
            raise SystemExit(f'Bengali source missing: {path.relative_to(ROOT)}')
        text = path.read_text(encoding='utf-8')
        updated = text
        for source, target in EXACT_REPLACEMENTS.items():
            updated = updated.replace(source, target)
        for source, target in GLOBAL_REPLACEMENTS:
            updated = updated.replace(source, target)
        updated = unicodedata.normalize('NFC', updated)
        if updated != text:
            path.write_text(updated, encoding='utf-8')
            changed.append(str(path.relative_to(ROOT)))
    print(
        'Bengali native-copy finalizer updated: ' + ', '.join(changed)
        if changed
        else 'Bengali native-copy finalizer: source already finalized.'
    )


if __name__ == '__main__':
    main()
